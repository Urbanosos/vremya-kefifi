// Packs assets/kefifi/*.png into assets/kefifi/images.js as data URLs: node tools/pack-images.mjs
// Why: when index.html is opened by double click (file://), Chrome refuses to upload file images into WebGL
// textures (cross-origin). Data URLs are same-origin, so 3D textures work without a server.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'kefifi');
const out = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.png')).sort())
  out[path.basename(f, '.png')] = 'data:image/png;base64,' + fs.readFileSync(path.join(dir, f)).toString('base64');
fs.writeFileSync(path.join(dir, 'images.js'), `// Generated by tools/pack-images.mjs, do not edit by hand.\nwindow.KEFIFI_IMG = ${JSON.stringify(out)};\n`);
// dance animation frames cut from the dance video (кефифи/пример танца.MP4)
const ddir = path.join(dir, 'dance');
const frames = fs.existsSync(ddir) ? fs.readdirSync(ddir).filter(f => f.endsWith('.png')).sort()
  .map(f => 'data:image/png;base64,' + fs.readFileSync(path.join(ddir, f)).toString('base64')) : [];
fs.writeFileSync(path.join(dir, 'dance.js'), `// Generated by tools/pack-images.mjs, do not edit by hand.\nwindow.KEFIFI_DANCE = ${JSON.stringify(frames)};\n`);
console.log('dance frames:', frames.length, Math.round(fs.statSync(path.join(dir, 'dance.js')).size / 1024) + ' KB');
console.log('packed:', Object.keys(out).join(', '), Math.round(fs.statSync(path.join(dir, 'images.js')).size / 1024) + ' KB');
